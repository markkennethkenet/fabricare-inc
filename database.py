import time
import tempfile
from contextlib import contextmanager
from functools import lru_cache

import mysql.connector
from mysql.connector import Error as MySqlError

from db_config import DbConfig


class PostgresUnavailable(RuntimeError):
    """The PostgreSQL driver reported a database error."""


@lru_cache(maxsize=1)
def _ca_file(pem):
    # Aiven's CA is public, but keep deployment configuration out of source.
    with tempfile.NamedTemporaryFile(mode="w", suffix=".pem", delete=False,
                                     encoding="ascii") as certificate:
        certificate.write(pem)
        return certificate.name


def _connect(use_database=True):
    if DbConfig.postgres_dsn:
        return _connect_postgres()
    kwargs = {
        "host": DbConfig.host,
        "port": DbConfig.port,
        "user": DbConfig.user,
        "password": DbConfig.password,
        "connection_timeout": 5,
    }
    if use_database:
        kwargs["database"] = DbConfig.database
    ca = _ca_file(DbConfig.ssl_ca_pem) if DbConfig.ssl_ca_pem else DbConfig.ssl_ca
    if ca:
        kwargs.update(ssl_ca=ca, ssl_verify_cert=True, ssl_verify_identity=True,
                      ssl_disabled=False)
    elif DbConfig.host.endswith(".aivencloud.com"):
        raise ValueError("Configure MYSQL_SSL_CA_PEM or MYSQL_SSL_CA for Aiven TLS verification.")
    return mysql.connector.connect(**kwargs)


def _connect_postgres():
    import psycopg
    from psycopg.conninfo import conninfo_to_dict

    params = conninfo_to_dict(DbConfig.postgres_dsn)
    ca = (_ca_file(DbConfig.postgres_ssl_ca_pem) if DbConfig.postgres_ssl_ca_pem
          else DbConfig.postgres_ssl_ca)
    if ca:
        params.update(sslrootcert=ca, sslmode="verify-full")
    elif params.get("host") not in {"localhost", "127.0.0.1", "::1"}:
        raise PostgresUnavailable("Configure the PostgreSQL CA for the remote database.")
    params["connect_timeout"] = 5
    return psycopg.connect(**params)


@contextmanager
def get_connection(use_database=True):
    if DbConfig.postgres_dsn:
        import psycopg

        try:
            with _connect_postgres() as conn:
                yield conn
        except psycopg.Error:
            raise PostgresUnavailable("PostgreSQL operation failed.") from None
        return

    conn = _connect(use_database=use_database)
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def ensure_database_exists():
    with get_connection(use_database=False) as conn:
        cursor = conn.cursor()
        cursor.execute(
            f"CREATE DATABASE IF NOT EXISTS `{DbConfig.database}` "
            "CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci"
        )
        cursor.close()


def init_schema():
    if DbConfig.postgres_dsn:
        with get_connection() as conn:
            init_postgres_schema(conn)
        return
    ensure_database_exists()
    with get_connection() as conn:
        cursor = conn.cursor()
        cursor.execute(
            """
            CREATE TABLE IF NOT EXISTS users (
                id INT AUTO_INCREMENT PRIMARY KEY,
                full_name VARCHAR(255) NOT NULL,
                email VARCHAR(255) NOT NULL UNIQUE,
                password_hash VARCHAR(255) NOT NULL,
                phone VARCHAR(50) NOT NULL DEFAULT '',
                location VARCHAR(255) NOT NULL DEFAULT '',
                created_at BIGINT NOT NULL
            ) ENGINE=InnoDB
            """
        )
        cursor.execute(
            """
            CREATE TABLE IF NOT EXISTS auth_tokens (
                token VARCHAR(64) PRIMARY KEY,
                user_id INT NOT NULL,
                created_at BIGINT NOT NULL,
                expires_at BIGINT NULL,
                CONSTRAINT fk_auth_user
                    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
                INDEX idx_auth_user_id (user_id)
            ) ENGINE=InnoDB
            """
        )
        cursor.close()


def init_postgres_schema(conn):
    with conn.cursor() as cursor:
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                full_name VARCHAR(255) NOT NULL,
                email VARCHAR(255) NOT NULL UNIQUE,
                password_hash VARCHAR(255) NOT NULL,
                phone VARCHAR(50) NOT NULL DEFAULT '',
                location VARCHAR(255) NOT NULL DEFAULT '',
                created_at BIGINT NOT NULL
            )
        """)
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS auth_tokens (
                token VARCHAR(64) PRIMARY KEY,
                user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                created_at BIGINT NOT NULL,
                expires_at BIGINT
            )
        """)
        cursor.execute("CREATE INDEX IF NOT EXISTS idx_auth_user_id ON auth_tokens(user_id)")


def insert_user(conn, full_name, email, password_hash, created_at):
    sql = """
        INSERT INTO users (full_name, email, password_hash, phone, location, created_at)
        VALUES (%s, %s, %s, '', '', %s)
    """
    with conn.cursor() as cursor:
        if DbConfig.postgres_dsn:
            cursor.execute(sql + " RETURNING id", (full_name, email, password_hash, created_at))
            return cursor.fetchone()[0]
        cursor.execute(sql, (full_name, email, password_hash, created_at))
        return cursor.lastrowid


def ping_database():
    with get_connection() as conn:
        cursor = conn.cursor()
        cursor.execute("SELECT 1")
        cursor.fetchone()
        cursor.close()
    return True


def db_error_message(exc):
    if isinstance(exc, MySqlError):
        return str(exc)
    return str(exc)
