import 'dart:convert';
import 'dart:io';
import 'package:hive/hive.dart';
import 'package:path/path.dart' as p;
import '../models/scan_result.dart';

/// Hive keeps nested scan records without native database bindings or adapters.
///
/// On phones and desktops, [root] is the app's support directory and scan photos
/// are copied into it. On the web there is no file system: pass a null [root],
/// and Hive stores records in IndexedDB with each photo embedded as a data URL.
class HistoryStore {
  final Directory? root;
  late Box<String> _box;
  HistoryStore(this.root);

  bool get _inBrowser => root == null;

  Future<void> open() async {
    final root = this.root;
    if (root == null) {
      _box = await Hive.openBox<String>('scan_history');
      return;
    }
    await root.create(recursive: true);
    _box = await Hive.openBox<String>('scan_history',
        path: p.join(root.path, 'database'));
  }

  String _key(String userId, String id) => '$userId:$id';
  List<ScanResult> forUser(String userId) => _box.values
      .map((s) => ScanResult.fromJson(jsonDecode(s) as Map<String, dynamic>))
      .where((s) => s.userId == userId)
      .toList()
    ..sort((a, b) => b.dateScanned.compareTo(a.dateScanned));

  Future<ScanResult> add(ScanResult scan) async {
    // Numeric account/scan IDs are generated by the existing auth API and client.
    if (!RegExp(r'^\d+$').hasMatch(scan.userId) ||
        !RegExp(r'^\d+$').hasMatch(scan.id)) {
      throw ArgumentError('Invalid account or scan ID');
    }
    if (_inBrowser) {
      final images = [
        for (final source in scan.images)
          ScanImage(view: source.view, path: await _dataUrl(source)),
      ];
      final saved = scan.withImages(images);
      await put(saved);
      return saved;
    }
    final directory =
        Directory(p.join(root!.path, 'scan_media', scan.userId, scan.id));
    await directory.create(recursive: true);
    try {
      final images = <ScanImage>[];
      for (var i = 0; i < scan.images.length; i++) {
        final source = scan.images[i];
        final target = p.join(directory.path, '$i${p.extension(source.path)}');
        await source.file.copy(target);
        images.add(ScanImage(view: source.view, path: target));
      }
      final saved = scan.withImages(images);
      await put(saved);
      return saved;
    } catch (_) {
      await directory.delete(recursive: true);
      rethrow;
    }
  }

  /// Saves a changed scan under its existing ID, for example after another
  /// view was added. Photos already in the scan's media folder stay as they
  /// are; only new photos are copied in (or embedded, on the web).
  Future<ScanResult> replace(ScanResult scan) async {
    if (_inBrowser) {
      final images = [
        for (final source in scan.images)
          ScanImage(view: source.view, path: await _dataUrl(source)),
      ];
      final saved = scan.withImages(images);
      await put(saved);
      return saved;
    }
    final directory =
        Directory(p.join(root!.path, 'scan_media', scan.userId, scan.id));
    await directory.create(recursive: true);
    final media = p.normalize(p.absolute(directory.path));
    final copied = <File>[];
    try {
      final images = <ScanImage>[];
      for (final source in scan.images) {
        if (p.isWithin(media, p.normalize(p.absolute(source.path)))) {
          images.add(source);
          continue;
        }
        final target = p.join(directory.path,
            '${source.view}_${DateTime.now().microsecondsSinceEpoch}${p.extension(source.path)}');
        await source.file.copy(target);
        copied.add(File(target));
        images.add(ScanImage(view: source.view, path: target));
      }
      final saved = scan.withImages(images);
      await put(saved);
      return saved;
    } catch (_) {
      for (final file in copied) {
        if (await file.exists()) await file.delete();
      }
      rethrow;
    }
  }

  /// Blob URLs expire with the browser session, so embed the photo itself.
  static Future<String> _dataUrl(ScanImage image) async {
    if (image.path.startsWith('data:')) return image.path;
    final bytes = await image.readBytes();
    final png = bytes.length > 3 &&
        bytes[0] == 0x89 &&
        bytes[1] == 0x50 &&
        bytes[2] == 0x4E;
    return 'data:image/${png ? 'png' : 'jpeg'};base64,${base64Encode(bytes)}';
  }

  Future<void> put(ScanResult scan) =>
      _box.put(_key(scan.userId, scan.id), jsonEncode(scan.toJson()));

  Future<void> delete(String userId, String id) async {
    final key = _key(userId, id);
    final raw = _box.get(key);
    if (raw == null) return;
    final root = this.root;
    if (root != null) {
      final scan =
          ScanResult.fromJson(jsonDecode(raw) as Map<String, dynamic>);
      final mediaRoot =
          p.normalize(p.absolute(p.join(root.path, 'scan_media')));
      for (final image in scan.images) {
        final imagePath = p.normalize(p.absolute(image.path));
        if (p.isWithin(mediaRoot, imagePath) &&
            await File(imagePath).exists()) {
          await File(imagePath).delete();
        }
      }
    }
    await _box.delete(key);
  }

  Future<void> clear(String userId) async {
    for (final scan in forUser(userId)) {
      await delete(userId, scan.id);
    }
  }

  Future<void> close() => _box.close();
}
